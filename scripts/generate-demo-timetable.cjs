// Generate the offline fixture from the user-supplied ICS; no school credentials or network access.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const input = fs.readFileSync(path.join(root,
  'entry/src/main/resources/rawfile/demo/timetable-2026-2027-1.ics'), 'utf8');
const lines = input.replace(/^\uFEFF/, '').split(/\r\n|\n|\r/);
const kept = [];
let alarm = false;
for (const line of lines) {
  if (line === 'BEGIN:VALARM') alarm = true;
  if (!alarm && /^(?:BEGIN:VCALENDAR|END:VCALENDAR|VERSION:|X-WR-CALNAME:|BEGIN:VEVENT|END:VEVENT|UID:|DTSTART;TZID=Asia\/Shanghai:|DTEND;TZID=Asia\/Shanghai:|SUMMARY:|LOCATION:|DESCRIPTION:)/.test(line)) {
    kept.push(line);
  }
  if (line === 'END:VALARM') alarm = false;
}
const output = '// Generated by scripts/generate-demo-timetable.cjs from the bundled original ICS.\n' +
  '// Calendar data only; alarm actions and unrelated calendar metadata are not executed.\n' +
  'export const DEMO_TIMETABLE_ICS: string = [\n' +
  kept.map(line => '  ' + JSON.stringify(line)).join(',\n') + '\n].join("\\n");\n';
fs.writeFileSync(path.join(root, 'entry/src/main/ets/feature/eas/demo/DemoTimetableSource.ets'), output);
